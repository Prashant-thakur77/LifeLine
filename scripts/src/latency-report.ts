import { percentile } from "@lifeline/keeper";
import { KEEPER_POLL_INTERVAL_SEC } from "@lifeline/shared";

/** One pass through what the keeper does between seeing low health and sending. */
export type DecisionSample = {
  at: string;
  address: string;
  readMs: number; // Hyperliquid clearinghouseState, the read that sees health below trigger
  probeMs: number; // dry quote that reads 1Click's fee
  quoteMs: number; // the sized quote
  freshMs: number; // Hyperliquid again, just before deciding
  totalMs: number;
  timeEstimateSec: number | null; // 1Click's own estimate from the quote
};

/** An attempt that didn't finish: in production the keeper would retry it. */
export type FailedAttempt = { at: string; error: string };

/** One rescue transaction, sent and waited on until it executed. */
export type NearSample = { at: string; txHash: string; ms: number; network: "testnet" | "mainnet" };

type Spread = { p50: number; p95: number };

const spread = (values: number[]): Spread => ({ p50: percentile(values, 50) ?? 0, p95: percentile(values, 95) ?? 0 });

function mostCommon(values: number[]): number | null {
  const counts = new Map<number, number>();
  for (const value of values) counts.set(value, (counts.get(value) ?? 0) + 1);
  let best: number | null = null;
  for (const [value, count] of counts) if (best === null || count > (counts.get(best) ?? 0)) best = value;
  return best;
}

export function summarize(decisions: DecisionSample[], near: NearSample[], failed: FailedAttempt[] = [], nearFailed: FailedAttempt[] = []) {
  return {
    failed,
    nearFailed,
    decision: {
      count: decisions.length,
      readMs: spread(decisions.map((s) => s.readMs)),
      probeMs: spread(decisions.map((s) => s.probeMs)),
      quoteMs: spread(decisions.map((s) => s.quoteMs)),
      freshMs: spread(decisions.map((s) => s.freshMs)),
      totalMs: spread(decisions.map((s) => s.totalMs)),
    },
    near: near.length === 0 ? null : { count: near.length, network: near[0]?.network ?? "testnet", ms: spread(near.map((s) => s.ms)) },
    oneClickEstimateSec: mostCommon(decisions.flatMap((s) => (s.timeEstimateSec === null ? [] : [s.timeEstimateSec]))),
  };
}

export type LatencySummary = ReturnType<typeof summarize>;

const sec = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

export function formatReport(summary: LatencySummary, generatedAt: string): string {
  const { decision, near, oneClickEstimateSec, failed, nearFailed } = summary;
  const nearNote =
    nearFailed.length === 0
      ? ""
      : ` ${nearFailed.length} of ${(near?.count ?? 0) + nearFailed.length} rescue transactions didn't come back from the public node and aren't in the table: ${[...new Set(nearFailed.map((f) => f.error))].join("; ")}.`;
  const attempts = decision.count + failed.length;
  const reasons = [...new Set(failed.map((f) => f.error))];
  const pollMs = KEEPER_POLL_INTERVAL_SEC * 1000;
  const rows = [
    `| Keeper decision, mainnet APIs | ${decision.count} | ${sec(decision.totalMs.p50)} | ${sec(decision.totalMs.p95)} |`,
    `| &nbsp;&nbsp;Hyperliquid read | ${decision.count} | ${sec(decision.readMs.p50)} | ${sec(decision.readMs.p95)} |`,
    `| &nbsp;&nbsp;1Click fee probe (dry quote) | ${decision.count} | ${sec(decision.probeMs.p50)} | ${sec(decision.probeMs.p95)} |`,
    `| &nbsp;&nbsp;1Click sized quote (dry) | ${decision.count} | ${sec(decision.quoteMs.p50)} | ${sec(decision.quoteMs.p95)} |`,
    `| &nbsp;&nbsp;Hyperliquid re-read | ${decision.count} | ${sec(decision.freshMs.p50)} | ${sec(decision.freshMs.p95)} |`,
    near === null
      ? "| NEAR rescue transaction | not sampled | | |"
      : `| NEAR rescue transaction, ${near.network} | ${near.count} | ${sec(near.ms.p50)} | ${sec(near.ms.p95)} |`,
  ];
  const estimate = oneClickEstimateSec === null ? null : oneClickEstimateSec * 1000;
  const total = (detect: number, part: "p50" | "p95") =>
    detect + decision.totalMs[part] + (near?.ms[part] ?? 0) + (estimate ?? 0);

  return [
    "# Rescue latency",
    "",
    `Generated by \`pnpm latency\` on ${generatedAt}. Nearest-rank percentiles, so each figure is a time that really happened.`,
    "",
    "| Step | Samples | p50 | p95 |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
    `The keeper decision is everything the keeper does between reading health below the trigger and sending the rescue: the same calls in the same order, against the real Hyperliquid and 1Click APIs. The quotes are dry here, so nothing is deposited. The policy check itself takes well under a millisecond and isn't listed.`,
    "",
    failed.length === 0
      ? `All ${attempts} attempts finished.`
      : `${failed.length} of ${attempts} attempts failed and aren't in the table: ${reasons.join("; ")}. In production the keeper writes a failed attempt to the audit log and tries again 30 s later.`,
    "",
    near === null
      ? "The NEAR transaction was not sampled in this run."
      : `The NEAR transaction is the vault's \`rescue\`, signed with the keeper's function-call key and waited on until it executed: the storage registration, the USDC transfer and the callback. ${near.network === "testnet" ? "It ran on testnet, where blocks come at the same pace as mainnet." : ""}`.trim() + nearNote,
    "",
    estimate === null
      ? "1Click gave no time estimate."
      : `After that, 1Click has to swap and deliver to Hyperliquid. That part is not measured until a rescue moves real money. 1Click's own estimate in every quote was ${oneClickEstimateSec} s.`,
    "",
    `Adding it up: the keeper looks every ${KEEPER_POLL_INTERVAL_SEC} s, so it sees a drop ${sec(pollMs / 2)} later on average and at most ${sec(pollMs)}. With 1Click's estimate, a rescue would take about ${sec(total(pollMs / 2, "p50"))} at p50 and ${sec(total(pollMs, "p95"))} at p95, from the moment health crosses the trigger to USDC in the Hyperliquid account. Real rescues replace this estimate in \`/api/stats\`, which reports the measured time from detection to credit.`,
    "",
  ].join("\n");
}
